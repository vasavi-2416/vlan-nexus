import React, { useState, useEffect } from 'react';
import {
  Radio,
  GitFork,
  ArrowRight,
  Play,
  RotateCcw,
  CheckCircle2,
  AlertTriangle,
  Server,
  Shield,
  Layers,
  Cpu,
} from 'lucide-react';
import { StorageService } from '../services/storage';
import { RouterSubinterface } from '../types';

export const InterVlanRouting: React.FC = () => {
  const [subinterfaces, setSubinterfaces] = useState<RouterSubinterface[]>([]);
  const [activeStep, setActiveStep] = useState<number>(0);
  const [isSimulating, setIsSimulating] = useState<boolean>(false);
  const [simulationSpeed, setSimulationSpeed] = useState<number>(1200);

  useEffect(() => {
    setSubinterfaces(StorageService.getSubinterfaces());
  }, []);

  const packetFlowSteps = [
    {
      step: 1,
      title: 'STEP 01 — Student-PC1 (192.168.10.10)',
      node: 'Student-PC1',
      subnode: '192.168.10.10',
      vlan: 'VLAN 10',
      description: 'Packet Origin: Un-tagged Ethernet frame generated by Student-PC1 targeted for Faculty-PC1 (192.168.20.10).',
      icon: <Server className="w-5 h-5 text-blue-400" />,
      tag: 'Un-tagged Frame',
    },
    {
      step: 2,
      title: 'STEP 02 — S1-SWITCH Access Port Ingress',
      node: 'S1-SWITCH Access Port',
      subnode: 'Fa0/2 Ingress',
      vlan: 'VLAN 10',
      description: 'Access Port Ingress: Frame arrives on S1-SWITCH port Fa0/2 assigned to VLAN 10.',
      icon: <GitFork className="w-5 h-5 text-blue-400" />,
      tag: 'Port Fa0/2 (VLAN 10)',
    },
    {
      step: 3,
      title: 'STEP 03 — S1-SWITCH Trunk Port Egress',
      node: 'S1-SWITCH Trunk Port',
      subnode: 'Fa0/1 Egress',
      vlan: '802.1Q Tag: 10',
      description: 'Trunk Port Egress: Switch appends 802.1Q Tag 10 to frame header and forwards across Fa0/1 trunk to R1-ROUTER.',
      icon: <Layers className="w-5 h-5 text-purple-400" />,
      tag: '802.1Q Tag: 10',
    },
    {
      step: 4,
      title: 'STEP 04 — R1-ROUTER Subinterface Ingress',
      node: 'R1-ROUTER Subinterface',
      subnode: 'G0/0.10 (192.168.10.1)',
      vlan: 'Gateway Ingress',
      description: 'Subinterface Ingress: R1-ROUTER interface G0/0.10 receives 802.1Q tagged frame, strips tag 10, and routes L3 packet.',
      icon: <Radio className="w-5 h-5 text-cyan-400" />,
      tag: 'G0/0.10 Ingress',
    },
    {
      step: 5,
      title: 'STEP 05 — R1-ROUTER Layer 3 Routing',
      node: 'R1-ROUTER L3 Engine',
      subnode: 'Routing Table Lookup',
      vlan: 'Routing Decision',
      description: 'Layer 3 Routing: Routing table identifies destination network 192.168.20.0/24 reachable via subinterface G0/0.20.',
      icon: <Cpu className="w-5 h-5 text-amber-400" />,
      tag: '192.168.20.0/24 via G0/0.20',
    },
    {
      step: 6,
      title: 'STEP 06 — R1-ROUTER Subinterface Egress',
      node: 'R1-ROUTER Subinterface',
      subnode: 'G0/0.20 Egress',
      vlan: '802.1Q Tag: 20',
      description: 'Subinterface Egress: Subinterface G0/0.20 prepends 802.1Q Tag 20 and transmits frame out physical G0/0 port back to switch.',
      icon: <Layers className="w-5 h-5 text-purple-400" />,
      tag: '802.1Q Tag: 20',
    },
    {
      step: 7,
      title: 'STEP 07 — S1-SWITCH Destination Delivery',
      node: 'S1-SWITCH Fa0/4 → Faculty-PC1',
      subnode: 'Fa0/4 Egress',
      vlan: 'Faculty-PC1 (192.168.20.10)',
      description: 'Destination Delivery: S1-SWITCH receives VLAN 20 frame on Fa0/1 trunk, strips 802.1Q tag, and delivers untagged frame to Faculty-PC1 on Fa0/4.',
      icon: <CheckCircle2 className="w-5 h-5 text-emerald-400" />,
      tag: 'DELIVERED — 0% LOSS',
    },
  ];

  const startSimulation = () => {
    setIsSimulating(true);
    setActiveStep(1);
  };

  useEffect(() => {
    if (isSimulating && activeStep > 0 && activeStep < packetFlowSteps.length) {
      const timer = setTimeout(() => {
        setActiveStep((prev) => prev + 1);
      }, simulationSpeed);
      return () => clearTimeout(timer);
    } else if (activeStep === packetFlowSteps.length) {
      setIsSimulating(false);
    }
  }, [isSimulating, activeStep, simulationSpeed]);

  const resetSimulation = () => {
    setIsSimulating(false);
    setActiveStep(0);
  };

  return (
    <div className="p-4 md:p-8 space-y-6 max-w-[1600px] mx-auto">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl md:text-3xl font-extrabold tracking-tight text-slate-100 flex items-center gap-2.5">
            <Radio className="w-7 h-7 text-cyan-400" /> Router-on-a-Stick Inter-VLAN Routing
          </h1>
          <p className="text-xs md:text-sm text-slate-400 mt-1 font-medium">
            Authoritative Cisco 2911 Router subinterfaces (G0/0.10, G0/0.20, G0/0.30) with 802.1Q trunking to Cisco 2960 Switch.
          </p>
        </div>

        {/* Simulation Controls */}
        <div className="flex items-center space-x-3">
          <button
            onClick={startSimulation}
            disabled={isSimulating}
            className="px-4 py-2.5 rounded-xl bg-cyan-500 hover:bg-cyan-400 disabled:opacity-50 text-slate-950 font-bold text-xs uppercase tracking-wider shadow-lg shadow-cyan-500/20 flex items-center gap-2"
          >
            <Play className="w-4 h-4 fill-current" />
            <span>{isSimulating ? 'SIMULATION RUNNING...' : 'START PACKET SIMULATION'}</span>
          </button>
          <button
            onClick={resetSimulation}
            className="p-2.5 rounded-xl bg-slate-900 border border-slate-800 text-slate-400 hover:text-white hover:bg-slate-800"
            title="Reset Simulation"
          >
            <RotateCcw className="w-4 h-4" />
          </button>
        </div>
      </div>

      {/* Authoritative Subinterfaces Table */}
      <div className="rounded-3xl bg-slate-900/90 border border-slate-800 shadow-xl overflow-hidden p-6 space-y-4">
        <h3 className="text-xs font-extrabold uppercase tracking-wider text-slate-200 flex items-center gap-2">
          <Server className="w-4 h-4 text-cyan-400" /> R1-ROUTER Subinterface Configuration Table
        </h3>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs text-slate-300">
            <thead className="bg-slate-950/80 uppercase text-[10px] tracking-wider text-slate-400 border-b border-slate-800">
              <tr>
                <th className="px-5 py-3.5">Subinterface</th>
                <th className="px-5 py-3.5">Assigned VLAN</th>
                <th className="px-5 py-3.5">802.1Q Encapsulation</th>
                <th className="px-5 py-3.5">Gateway IP Address</th>
                <th className="px-5 py-3.5">Subnet Mask</th>
                <th className="px-5 py-3.5">Status</th>
                <th className="px-5 py-3.5 text-right">SIMULATED THROUGHPUT</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-800/60 font-mono">
              {subinterfaces.map((sub) => (
                <tr key={sub.name} className="hover:bg-slate-800/40">
                  <td className="px-5 py-4 font-bold text-cyan-400">{sub.name}</td>
                  <td className="px-5 py-4 font-sans whitespace-nowrap">
                    <span
                      className="px-3 py-1 rounded-full text-[10px] font-extrabold border uppercase whitespace-nowrap inline-flex items-center tracking-wider"
                      style={{
                        backgroundColor: sub.vlanId === 10 ? 'rgba(59, 130, 246, 0.15)' : sub.vlanId === 20 ? 'rgba(139, 92, 246, 0.15)' : 'rgba(6, 182, 212, 0.15)',
                        borderColor: sub.vlanId === 10 ? '#3B82F6' : sub.vlanId === 20 ? '#8B5CF6' : '#06B6D4',
                        color: sub.vlanId === 10 ? '#60A5FA' : sub.vlanId === 20 ? '#C084FC' : '#22D3EE',
                      }}
                    >
                      VLAN {sub.vlanId} - {sub.vlanName}
                    </span>
                  </td>
                  <td className="px-5 py-4 text-purple-400 font-bold">{sub.encapsulation}</td>
                  <td className="px-5 py-4 font-bold text-slate-100">{sub.ipAddress}</td>
                  <td className="px-5 py-4 text-slate-400">{sub.subnetMask}</td>
                  <td className="px-5 py-4 font-sans">
                    <span className="px-2.5 py-1 rounded-full bg-emerald-950 text-emerald-400 border border-emerald-800 text-[10px] font-bold flex items-center gap-1.5 w-fit">
                      <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-pulse" />
                      {sub.status}
                    </span>
                  </td>
                  <td className="px-5 py-4 text-right text-slate-400 text-[11px]">
                    RX: {sub.rxBytes} | TX: {sub.txBytes}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Interactive 7-Step Packet Traversal Stepper */}
      <div className="rounded-3xl bg-slate-900/90 border border-slate-800 shadow-2xl p-6 space-y-6">
        <div className="flex items-center justify-between border-b border-slate-800 pb-4">
          <div>
            <h3 className="text-sm font-extrabold uppercase tracking-wider text-slate-100 flex items-center gap-2">
              <Layers className="w-4 h-4 text-cyan-400" /> 7-Step 802.1Q Inter-VLAN Packet Traversal Simulation
            </h3>
            <p className="text-xs text-slate-400 mt-0.5 font-mono">
              Student-PC1 (192.168.10.10 VLAN 10) → S1-SWITCH Fa0/2 → Fa0/1 Trunk → R1-ROUTER G0/0.10 → G0/0.20 → Fa0/4 → Faculty-PC1 (192.168.20.10 VLAN 20)
            </p>
          </div>

          <div className="flex items-center space-x-2 text-xs font-mono">
            <span className="text-slate-400">Simulation Speed:</span>
            <button
              onClick={() => setSimulationSpeed(800)}
              className={`px-2.5 py-1 rounded-lg ${simulationSpeed === 800 ? 'bg-cyan-500 text-slate-950 font-bold' : 'bg-slate-950 text-slate-400'}`}
            >
              Fast (1.5x)
            </button>
            <button
              onClick={() => setSimulationSpeed(1200)}
              className={`px-2.5 py-1 rounded-lg ${simulationSpeed === 1200 ? 'bg-cyan-500 text-slate-950 font-bold' : 'bg-slate-950 text-slate-400'}`}
            >
              Normal (1.0x)
            </button>
          </div>
        </div>

        {/* 7-Step Grid Stepper */}
        <div className="grid grid-cols-1 md:grid-cols-7 gap-2.5">
          {packetFlowSteps.map((stepItem) => {
            const isActive = activeStep === stepItem.step;
            const isPassed = activeStep > stepItem.step;

            return (
              <div
                key={stepItem.step}
                onClick={() => setActiveStep(stepItem.step)}
                className={`p-3 rounded-2xl border transition-all cursor-pointer text-left space-y-2 relative ${
                  isActive
                    ? 'bg-cyan-950/90 border-cyan-400 shadow-xl shadow-cyan-500/25 ring-2 ring-cyan-400/50 scale-105 z-10'
                    : isPassed
                    ? 'bg-slate-950 border-emerald-800/80 text-slate-200'
                    : 'bg-slate-950/60 border-slate-800/60 opacity-60 text-slate-500'
                }`}
              >
                <div className="flex items-center justify-between">
                  <span className="text-[10px] font-mono font-bold text-slate-400">STEP 0{stepItem.step}</span>
                  {isPassed ? <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" /> : stepItem.icon}
                </div>
                <div className="font-bold text-[11px] truncate leading-tight text-slate-100">{stepItem.node}</div>
                <div className="text-[9px] font-mono text-cyan-400 truncate">{stepItem.tag}</div>
              </div>
            );
          })}
        </div>

        {/* Active Step Highlight Banner */}
        {activeStep > 0 && activeStep <= packetFlowSteps.length && (
          <div className="p-5 rounded-2xl bg-slate-950 border border-cyan-500/40 shadow-2xl flex flex-col md:flex-row md:items-center justify-between gap-4 animate-in fade-in">
            <div className="flex items-start space-x-4">
              <div className="p-3.5 rounded-2xl bg-cyan-950 border border-cyan-800 shrink-0">
                {packetFlowSteps[activeStep - 1].icon}
              </div>
              <div className="space-y-1">
                <div className="text-xs font-mono font-bold text-cyan-400 uppercase tracking-widest">
                  Packet Location: Step {activeStep} of 7
                </div>
                <h4 className="text-base font-extrabold text-slate-100">
                  {packetFlowSteps[activeStep - 1].title}
                </h4>
                <p className="text-xs text-slate-300 leading-relaxed max-w-3xl">
                  {packetFlowSteps[activeStep - 1].description}
                </p>
              </div>
            </div>

            <div className="flex items-center gap-3 shrink-0">
              <div className="px-3 py-1.5 rounded-xl bg-slate-900 border border-slate-800 text-xs font-mono">
                <span className="text-slate-400">Header Tag State: </span>
                <span className="text-purple-400 font-bold">{packetFlowSteps[activeStep - 1].tag}</span>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
